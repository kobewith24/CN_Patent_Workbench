# -*- coding: utf-8 -*-
"""Build a 60-question seed eval set for the patent RAG.

30 factoid + 15 comparison + 15 unanswerable.
Questions are synthetic (generated by Qwen3 from title/IPC only) and should be
human-reviewed before being treated as a gold benchmark.
"""
import argparse
import json
import os
import random
import re
import time
from collections import defaultdict

import requests

ROOT = r"D:\Projects\CN_Patent_RAG"
SRC = os.path.join(ROOT, "data", "clean", "patents.jsonl")
OUT = os.path.join(ROOT, "eval", "gold.jsonl")
OLLAMA = "http://127.0.0.1:11434"
MODEL = "qwen3:4b-instruct-2507-q4_K_M"

FACTOID_PROMPT = """请根据下面这件专利的标题和 IPC，写一个中文技术问题。
要求：
1. 问题是技术人员会问的，必须检索该专利摘要才能回答；
2. 不要照抄标题，不要出现“本发明/本实用新型”；
3. 只输出问题本身，不要编号、不要解释、不要引号。

标题：{title}
IPC：{ipc}
"""

COMPARE_PROMPT = """请根据下面两件专利的标题，写一个中文对比问题，要求对比它们在技术方案上的差异。
只输出问题本身，不要编号、不要解释、不要引号。

A：{a}
B：{b}
"""

UNANSWERABLE_TEMPLATES = [
    "《{title}》的申请人名称是什么？",
    "《{title}》是否发生过专利诉讼？",
    "《{title}》目前的法律状态是授权还是失效？",
]


def ollama(prompt, num_predict=96):
    r = requests.post(OLLAMA + "/api/generate", json={
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
        "think": False,
        "options": {"temperature": 0.3, "num_predict": num_predict, "num_ctx": 2048},
    }, timeout=120)
    r.raise_for_status()
    text = (r.json().get("response") or "").strip()
    text = re.sub(r"^(问题|问：|Q[:：])\s*", "", text)
    text = text.split("\n")[0].strip().strip('"“”')
    return text


def sample():
    by_section = defaultdict(list)
    by_subclass = defaultdict(list)
    reservoir = []
    n = 0
    with open(SRC, encoding="utf-8") as f:
        for line in f:
            rec = json.loads(line)
            n += 1
            sec = rec["ipc_section"] or "NA"
            if len(by_section[sec]) < 40:
                by_section[sec].append(rec)
            sub = rec["ipc_subclass"] or "NA"
            if sub != "NA" and len(by_subclass[sub]) < 30:
                by_subclass[sub].append(rec)
            if len(reservoir) < 200:
                reservoir.append(rec)
            elif random.random() < 200 / n:
                reservoir[random.randrange(200)] = rec
    return by_section, by_subclass, reservoir


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--factoid", type=int, default=30)
    ap.add_argument("--compare", type=int, default=15)
    ap.add_argument("--unans", type=int, default=15)
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()

    random.seed(2026)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    by_section, by_subclass, reservoir = sample()

    per_section = max(4, args.factoid // max(1, len(by_section)) + 2)
    factoid = []
    for sec, recs in sorted(by_section.items()):
        for rec in recs[:per_section]:
            factoid.append(rec)
    random.shuffle(factoid)
    factoid = factoid[:args.factoid]

    subs = [s for s, recs in by_subclass.items() if len(recs) >= 2]
    random.shuffle(subs)
    pairs = []
    for sub in subs:
        recs = by_subclass[sub]
        pairs.append((recs[0], recs[1]))
        if len(pairs) >= args.compare:
            break

    unans = random.sample(reservoir, min(args.unans, len(reservoir)))

    rows = []
    t0 = time.time()
    for i, rec in enumerate(factoid, 1):
        try:
            q = ollama(FACTOID_PROMPT.format(title=rec["title"], ipc=rec["ipc_main"]))
        except Exception as exc:  # noqa: BLE001
            print("factoid err", i, exc, flush=True)
            continue
        if len(q) < 6:
            continue
        rows.append({
            "qid": "f%02d" % i, "question": q, "type": "factoid",
            "filters": {}, "gold_doc_ids": [rec["doc_id"]],
            "answerable": True, "synthetic": True,
        })
        print("f%02d %s" % (i, q), flush=True)

    for i, (a, b) in enumerate(pairs, 1):
        # Deterministic: the LLM tended to produce identical generic questions.
        q = "《%s》与《%s》在技术方案上的主要区别是什么？" % (a["title"], b["title"])
        rows.append({
            "qid": "c%02d" % i, "question": q, "type": "comparison",
            "filters": {}, "gold_doc_ids": [a["doc_id"], b["doc_id"]],
            "gold_titles": [a["title"], b["title"]],
            "answerable": True, "synthetic": True,
        })
        print("c%02d %s" % (i, q), flush=True)

    for i, rec in enumerate(unans, 1):
        q = UNANSWERABLE_TEMPLATES[(i - 1) % len(UNANSWERABLE_TEMPLATES)].format(title=rec["title"])
        rows.append({
            "qid": "u%02d" % i, "question": q, "type": "unanswerable",
            "filters": {}, "gold_doc_ids": [],
            "answerable": False, "synthetic": True,
        })
        print("u%02d %s" % (i, q), flush=True)

    with open(args.out, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("saved %d -> %s (%.1f min)" % (len(rows), args.out, (time.time() - t0) / 60))


if __name__ == "__main__":
    main()
